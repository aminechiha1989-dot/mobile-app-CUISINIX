-- Cuisinix : prix des ingrédients et quantités par personne
-- À exécuter dans le SQL Editor de Supabase (peut être relancé sans risque).

alter table public.ingredients
  add column if not exists price_dt numeric(8,2),
  add column if not exists price_unit text check (price_unit in ('kg','l','piece','box')),
  add column if not exists price_updated date,
  add column if not exists price_source text;

-- Quantité par personne : en g (prix au kg), en ml (prix au litre), en pièces ou en boîtes
